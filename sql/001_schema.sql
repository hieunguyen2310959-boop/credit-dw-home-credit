-- Home Credit coursework: core proposal only. PostgreSQL 16+.
-- Apply within a transaction; no existing data is dropped.
CREATE SCHEMA IF NOT EXISTS ops;
CREATE SCHEMA IF NOT EXISTS staging;
CREATE SCHEMA IF NOT EXISTS dw;
CREATE SCHEMA IF NOT EXISTS ml;
CREATE SCHEMA IF NOT EXISTS mart;

CREATE TABLE IF NOT EXISTS ops.etl_runs (
    etl_run_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    finished_at TIMESTAMPTZ,
    status TEXT NOT NULL DEFAULT 'running' CHECK (status IN ('running','succeeded','failed')),
    source_manifest JSONB NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(source_manifest)='object'),
    row_counts JSONB NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(row_counts)='object'),
    error_message TEXT,
    CHECK (finished_at IS NULL OR finished_at >= started_at),
    CHECK ((status='running' AND finished_at IS NULL) OR (status IN ('succeeded','failed') AND finished_at IS NOT NULL))
);

CREATE TABLE IF NOT EXISTS staging.application (
    "SK_ID_CURR" BIGINT PRIMARY KEY,
    "TARGET" SMALLINT CHECK ("TARGET" IN (0,1)),
    "NAME_CONTRACT_TYPE" TEXT,
    "AMT_INCOME_TOTAL" NUMERIC(20,4),
    "AMT_CREDIT" NUMERIC(20,4),
    "AMT_ANNUITY" NUMERIC(20,4),
    "AMT_GOODS_PRICE" NUMERIC(20,4),
    "DAYS_BIRTH" INTEGER,
    "DAYS_EMPLOYED" INTEGER,
    "NAME_INCOME_TYPE" TEXT,
    "NAME_EDUCATION_TYPE" TEXT,
    "OCCUPATION_TYPE" TEXT,
    "NAME_FAMILY_STATUS" TEXT,
    "CNT_CHILDREN" INTEGER,
    "CNT_FAM_MEMBERS" NUMERIC,
    "FLAG_OWN_CAR" TEXT,
    "FLAG_OWN_REALTY" TEXT,
    "EXT_SOURCE_1" DOUBLE PRECISION,
    "EXT_SOURCE_2" DOUBLE PRECISION,
    "EXT_SOURCE_3" DOUBLE PRECISION,
    data_source TEXT NOT NULL CHECK (data_source IN ('application_train','application_test')),
    etl_run_id BIGINT NOT NULL REFERENCES ops.etl_runs,
    source_file TEXT NOT NULL,
    CHECK (data_source <> 'application_test' OR "TARGET" IS NULL)
);

CREATE TABLE IF NOT EXISTS staging.previous_application (
    "SK_ID_PREV" BIGINT PRIMARY KEY,
    "SK_ID_CURR" BIGINT NOT NULL,
    "NAME_CONTRACT_STATUS" TEXT,
    "NAME_CONTRACT_TYPE" TEXT,
    "AMT_APPLICATION" NUMERIC(20,4),
    "AMT_CREDIT" NUMERIC(20,4),
    "DAYS_DECISION" INTEGER,
    etl_run_id BIGINT NOT NULL REFERENCES ops.etl_runs,
    source_file TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS previous_application_current_idx ON staging.previous_application ("SK_ID_CURR");

CREATE TABLE IF NOT EXISTS dw.dim_applicant_profile (
    applicant_profile_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_application_id BIGINT NOT NULL UNIQUE,
    age_years DOUBLE PRECISION CHECK (age_years >= 0 AND age_years < 'Infinity'::float8),
    age_band TEXT NOT NULL,
    education_level TEXT NOT NULL,
    income_type TEXT NOT NULL,
    occupation_type TEXT NOT NULL,
    family_status TEXT NOT NULL,
    cnt_children INTEGER CHECK (cnt_children >= 0),
    cnt_family_members INTEGER CHECK (cnt_family_members >= 0),
    flag_own_car BOOLEAN,
    flag_own_realty BOOLEAN,
    UNIQUE(applicant_profile_key, source_application_id)
);
CREATE TABLE IF NOT EXISTS dw.dim_contract_type (
    contract_type_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contract_type_name TEXT NOT NULL UNIQUE
);
INSERT INTO dw.dim_contract_type(contract_type_name) VALUES ('Unknown') ON CONFLICT DO NOTHING;

CREATE TABLE IF NOT EXISTS dw.fact_application (
    application_id BIGINT PRIMARY KEY,
    applicant_profile_key BIGINT NOT NULL UNIQUE,
    contract_type_key BIGINT NOT NULL REFERENCES dw.dim_contract_type,
    etl_run_id BIGINT NOT NULL REFERENCES ops.etl_runs,
    data_source TEXT NOT NULL CHECK (data_source IN ('application_train','application_test')),
    amt_income_total NUMERIC(20,4) CHECK (amt_income_total>=0),
    amt_credit NUMERIC(20,4) CHECK (amt_credit>=0),
    amt_annuity NUMERIC(20,4) CHECK (amt_annuity>=0),
    amt_goods_price NUMERIC(20,4) CHECK (amt_goods_price>=0),
    employment_days INTEGER CHECK (employment_days>=0),
    ext_source_1 DOUBLE PRECISION CHECK (ext_source_1 BETWEEN 0 AND 1),
    ext_source_2 DOUBLE PRECISION CHECK (ext_source_2 BETWEEN 0 AND 1),
    ext_source_3 DOUBLE PRECISION CHECK (ext_source_3 BETWEEN 0 AND 1),
    previous_application_count INTEGER NOT NULL CHECK (previous_application_count>=0),
    previous_approved_count INTEGER NOT NULL CHECK (previous_approved_count>=0),
    previous_refused_count INTEGER NOT NULL CHECK (previous_refused_count>=0),
    target SMALLINT CHECK (target IN (0,1)),
    FOREIGN KEY (applicant_profile_key,application_id)
        REFERENCES dw.dim_applicant_profile(applicant_profile_key,source_application_id),
    CHECK (previous_approved_count+previous_refused_count<=previous_application_count),
    CHECK (data_source<>'application_test' OR target IS NULL)
);
CREATE INDEX IF NOT EXISTS fact_application_contract_idx ON dw.fact_application(contract_type_key);

CREATE TABLE IF NOT EXISTS ml.model_runs (
    model_run_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model_name TEXT NOT NULL CHECK (length(trim(model_name))>0),
    feature_version TEXT NOT NULL,
    trained_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    artifact_path TEXT NOT NULL CHECK (length(trim(artifact_path))>0),
    data_snapshot_ref TEXT NOT NULL,
    split_seed INTEGER,
    evaluation_metrics JSONB NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(evaluation_metrics)='object')
);

-- Input feature snapshots cannot contain nested label keys, non-finite numeric
-- strings, or JSON scalar/array roots. JSON numeric NaN/Infinity is invalid itself.
CREATE OR REPLACE FUNCTION ml.valid_feature_json(value JSONB) RETURNS BOOLEAN
LANGUAGE plpgsql IMMUTABLE STRICT AS $$
DECLARE item RECORD; elem JSONB;
BEGIN
    IF jsonb_typeof(value)='object' THEN
        FOR item IN SELECT * FROM jsonb_each(value) LOOP
            IF lower(item.key) IN ('target','label','y','recommendation','risk_score') THEN RETURN false; END IF;
            IF NOT ml.valid_feature_json(item.value) THEN RETURN false; END IF;
        END LOOP;
    ELSIF jsonb_typeof(value)='array' THEN
        FOR elem IN SELECT * FROM jsonb_array_elements(value) LOOP
            IF NOT ml.valid_feature_json(elem) THEN RETURN false; END IF;
        END LOOP;
    ELSIF jsonb_typeof(value)='string' AND lower(value #>> '{}') IN ('nan','infinity','-infinity','inf','-inf') THEN
        RETURN false;
    END IF;
    RETURN true;
END $$;

CREATE TABLE IF NOT EXISTS ml.assessments (
    assessment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT NOT NULL REFERENCES dw.fact_application,
    model_run_id BIGINT NOT NULL REFERENCES ml.model_runs,
    assessed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    status TEXT NOT NULL CHECK (status IN ('succeeded','failed','not_ready')),
    feature_snapshot JSONB NOT NULL CHECK (jsonb_typeof(feature_snapshot)='object' AND ml.valid_feature_json(feature_snapshot)),
    risk_score DOUBLE PRECISION CHECK (risk_score BETWEEN 0 AND 1),
    risk_band TEXT,
    recommendation TEXT,
    policy_version TEXT NOT NULL,
    reason_codes JSONB NOT NULL DEFAULT '[]' CHECK (jsonb_typeof(reason_codes)='array'),
    CHECK ((status='succeeded' AND risk_score IS NOT NULL AND risk_band IS NOT NULL AND recommendation IS NOT NULL)
        OR (status IN ('failed','not_ready') AND risk_score IS NULL AND risk_band IS NULL AND recommendation IS NULL AND jsonb_array_length(reason_codes)>0))
);
CREATE INDEX IF NOT EXISTS assessments_latest_success_idx
    ON ml.assessments(application_id, assessed_at DESC, assessment_id DESC) WHERE status='succeeded';
CREATE INDEX IF NOT EXISTS assessments_model_idx ON ml.assessments(model_run_id);

-- Referenced models keep immutable metadata; changed artifacts require a new ID.
-- File-content integrity remains the responsibility of the future ML module.
CREATE OR REPLACE FUNCTION ml.protect_used_model() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW IS DISTINCT FROM OLD AND EXISTS (
        SELECT 1 FROM ml.assessments WHERE model_run_id=OLD.model_run_id
    ) THEN RAISE EXCEPTION 'Referenced model metadata is immutable; register a new model'; END IF;
    RETURN NEW;
END $$;
CREATE OR REPLACE TRIGGER protect_used_model BEFORE UPDATE ON ml.model_runs
FOR EACH ROW EXECUTE FUNCTION ml.protect_used_model();
