-- Bảng nghiệp vụ ghi nhận quyết định thẩm định (Web DSS); không chạy lại ETL để tạo bảng này.
CREATE SCHEMA IF NOT EXISTS app;

CREATE TABLE IF NOT EXISTS app.credit_decisions (
    decision_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT NOT NULL REFERENCES dw.fact_application(application_id),
    applicant_name TEXT NOT NULL,
    decision TEXT NOT NULL,
    reason_code TEXT,
    notes TEXT,
    officer_id TEXT,
    decided_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS credit_decisions_app_idx
    ON app.credit_decisions (application_id, decision_id DESC);
