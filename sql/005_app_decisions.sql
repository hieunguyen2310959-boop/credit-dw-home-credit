CREATE SCHEMA IF NOT EXISTS app;

CREATE TABLE IF NOT EXISTS app.credit_decisions (
    decision_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT,
    applicant_name TEXT,
    decision TEXT,
    reason_code TEXT,
    notes TEXT,
    officer_id TEXT,
    decided_at TIMESTAMPTZ DEFAULT now()
);

CREATE INDEX IF NOT EXISTS credit_decisions_app_idx
    ON app.credit_decisions (application_id, decision_id DESC);
